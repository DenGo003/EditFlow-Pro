'use strict';
const assert=require('node:assert/strict');
const G=require('../uxp/src/color-grade');
const V=require('../uxp/src/visual-tools');
const neutral={exposure_offset:0,contrast_offset:0,temperature_offset:0};
const natural=G.gradeFromAnalysis(neutral,'natural',.75);
assert.equal(natural.contrast_offset,9);
assert(natural.saturation>100);
const cinema=G.gradeFromAnalysis(neutral,'cinematic',.75);
assert(cinema.contrast_offset>natural.contrast_offset);
assert(cinema.saturation<100);
const warm=G.gradeFromAnalysis(neutral,'warm',.75);
assert(warm.temperature_offset>5);
assert(G.gradeFromAnalysis({contrast_offset:999},'cinematic',1).contrast_offset<=30);
const num=v=>({value:{value:v}});
const params=[['Basic Correction > Exposure',0],['Contrast',0],['Temperature',0],['Basic Correction > Saturation',100]].map(([name,start])=>{
 const p={displayName:name,val:start,isTimeVarying:()=>false,getStartValue:async()=>num(p.val),createKeyframe:v=>({value:v}),createSetValueAction:k=>({run:()=>{p.val=k.value}})};return p;
});
let disabled=false;
const fx={getMatchName:async()=> 'AE.ADBE Lumetri',getDisplayName:async()=> 'Lumetri Color',getParamCount:()=>params.length,getParam:i=>params[i]};
const layer={isAdjustmentLayer:async()=>true,isDisabled:async()=>disabled,getComponentChain:async()=>({getComponentCount:()=>1,getComponentAtIndex:()=>fx})};
const seq={guid:'abc',getVideoTrackCount:async()=>2,getVideoTrack:async i=>({getTrackItems:async()=>i===1?[layer]:[]})};
const project={getActiveSequence:async()=>seq,lockedAccess:f=>f(),executeTransaction:f=>{const actions=[];f({addAction:a=>actions.push(a)});actions.forEach(x=>x.run());return true}};
const ppro={Project:{getActiveProject:async()=>project}};
(async()=>{
 const pre=await V.inspectColorParamsOnTop(ppro);
 assert.equal(pre.layers[0].recognized.saturation.value,100);
 const r=await V.applyColorToTop(ppro,{guid:'abc'},{color:natural});
 assert.deepEqual(r.applied.map(x=>x.name),['contrast','saturation']);
 assert.equal(params[1].val,9);
 assert.equal(params[3].val,natural.saturation);
 const repeat=await V.applyColorToTop(ppro,{guid:'abc'},{color:cinema});
 assert(repeat.notes.some(x=>x.includes('protected')));
 assert(!repeat.applied.some(x=>['contrast','saturation'].includes(x.name)));
 const refresh=await V.applyColorToTop(ppro,{guid:'abc'},{color:cinema},{replaceExisting:true});
 assert(refresh.applied.length>=2);
 assert.equal(params[1].val,cinema.contrast_offset);
 disabled=true;
 await assert.rejects(V.applyColorToTop(ppro,{guid:'abc'},{color:cinema}),/DISABLED/);
 console.log('PASS M2.6.2: visible base looks, native Lumetri control labels, verified Before/After, protected existing grade, explicit Re-grade, disabled layer');
})().catch(e=>{console.error(e);process.exitCode=1});
